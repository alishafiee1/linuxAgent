export const dictionaries: Record<UiLanguage, Dict> = { fa, en };

export const I18n = createContext<{ t: Dict; lang: UiLanguage; setLang: (l: UiLanguage) => void }>({
  t: fa,
  lang: "fa",
  setLang: () => {},
});

/** Dates follow the panel language, so Persian text never holds scrambled English dates. */
export const useT = () => {
  const c = useContext(I18n);
  return { ...c, locale: c.lang === "fa" ? "fa-IR" : "en-GB" };
};
